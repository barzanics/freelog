def set_language(lang: str) -> None:
    """Switch the shared table in place ("fa" or "en") and the digit/calendar locale with it."""
    from ..core import persian
    if lang in ("fa", "en"):
        persian.set_locale(lang)
    if lang == "en":
        from .strings_en import EN
        S.clear(); S.update(EN)
    elif lang == "fa":
        S.clear(); S.update(_FA)
    else:
        raise ValueError("unsupported language")
